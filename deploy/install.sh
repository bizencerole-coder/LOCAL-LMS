# ---------------------------------------------------------------------------- 1. prerequisites
check_prerequisites() {
    section "1/7 Prerequisites"
    local os arch pretty="" id_like="" docker_fs video_fs free script

    os="$(uname -s)"; arch="$(uname -m)"
    if [ "$os" = Linux ] && [[ "$arch" =~ ^(x86_64|aarch64)$ ]]; then
        ok "64-bit Linux ($arch)"
    else
        stop "needs 64-bit Linux (x86_64 or aarch64); this is $os $arch"
    fi
    if [ -r /etc/os-release ]; then
        # shellcheck source=/dev/null
        pretty="$(. /etc/os-release && printf '%s' "${PRETTY_NAME:-}")"
        # shellcheck source=/dev/null
        id_like="$(. /etc/os-release && printf '%s %s' "${ID:-}" "${ID_LIKE:-}")"
        note "distribution: $pretty"
        case " $id_like " in *" debian "*|*" ubuntu "*) ;; *) warn "not Debian/Ubuntu based: untested, apt commands may not apply" ;; esac
    fi
    if [ -d /etc/openmediavault ] || command -v omv-confdbadm > /dev/null 2>&1; then
        IS_OMV=true
        note "OpenMediaVault detected: use an OMV shared folder for --video-root and keep the OMV web UI off student networks (setup guide section 3)"
    fi

    if [ "$EUID" -eq 0 ]; then
        warn "running as root: folders will be owned by root and no account joins the docker group; the setup guide assumes a sudo-capable operator account"
    elif command -v sudo > /dev/null 2>&1; then
        if $DRY_RUN; then
            ok "sudo available (not checked in a dry run)"
        elif sudo -v; then
            ok "sudo access for $OPERATOR"
        else
            stop "$OPERATOR cannot use sudo; log in as a sudo-capable operator account"
        fi
    else
        stop "sudo is not installed; as root run: apt-get install sudo && usermod -aG sudo $OPERATOR"
    fi

    [ -f compose.yaml ] && [ -d ../backend ] && [ -d nginx/templates ] \
        || stop "incomplete checkout: deploy/compose.yaml, backend/ or deploy/nginx/ missing"
    # A checkout made from a Windows commit can lack the executable bit on the scripts.
    for script in scripts/*.sh; do
        if [ ! -x "$script" ]; then
            run chmod +x install.sh scripts/*.sh
            note "operator scripts made executable"
            break
        fi
    done

    if command -v curl > /dev/null 2>&1; then
        ok "curl"
    elif command -v apt-get > /dev/null 2>&1; then
        note "curl missing: will be installed with apt-get"; APT_PACKAGES+=(curl ca-certificates)
    else
        stop "curl is missing and apt-get is unavailable"
    fi
    if PYTHON="$(find_python)"; then
        ok "$PYTHON $("$PYTHON" -c 'import sys; print("%d.%d.%d" % sys.version_info[:3])')"
    elif command -v apt-get > /dev/null 2>&1; then
        note "python3 >= 3.10 missing: will be installed with apt-get"; APT_PACKAGES+=(python3); PYTHON=python3
    else
        stop "python3 >= 3.10 is missing and apt-get is unavailable"
    fi

    docker_fs=/
    for docker_fs in /var/lib/docker /var/lib /; do [ -d "$docker_fs" ] && break; done
    free="$(free_gib "$docker_fs")"
    if [ -n "$free" ] && [ "$free" -ge "$MIN_DOCKER_FREE_GIB" ]; then
        ok "${free} GiB free on $docker_fs for Docker images and the database"
    else
        stop "only ${free:-?} GiB free on $docker_fs; Docker needs at least $MIN_DOCKER_FREE_GIB GiB"
    fi
    video_fs="$(existing_ancestor "$VIDEO_ROOT")"
    free="$(free_gib "$video_fs")"
    if [ -n "$free" ] && [ "$free" -ge "$MIN_VIDEO_FREE_GIB" ]; then
        ok "${free} GiB free on $video_fs for the video library"
    else
        warn "only ${free:-?} GiB free on $video_fs for the video library (demo videos ~0.3 GB; plan space for real lessons)"
    fi

    if [ ${#APT_PACKAGES[@]} -gt 0 ]; then
        confirm "Install ${APT_PACKAGES[*]} with apt-get now?" || die "Cancelled: install ${APT_PACKAGES[*]} and re-run."
        run as_root apt-get update -qq
        run as_root env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${APT_PACKAGES[@]}"
    fi
}

# ---------------------------------------------------------------------------- 2. docker
install_docker() {
    section "2/7 Docker Engine and Compose plugin"
    local tmp
    if docker compose version > /dev/null 2>&1; then
        skip "already installed: $(docker --version 2>/dev/null | tr -d '\r'); $(docker compose version 2>/dev/null | tr -d '\r')"
    else
        note "Docker Engine or the Compose plugin is missing."
        $IS_OMV && note "OMV: the openmediavault-compose plugin (OMV-Extras) is the alternative. Never run two container managers; answer no here if you plan to use the plugin."
        say "       Docker is installed with its official convenience script:"
        say "         $DOCKER_INSTALL_URL"
        say "       (to review it first: curl -fsSL $DOCKER_INSTALL_URL -o get-docker.sh && less get-docker.sh)"
        confirm "Download and run the Docker install script with sudo?" \
            || die "Cancelled. Install Docker by hand (docs/setup-guide.md section 2 or 3) and re-run."
        tmp="$WORK/get-docker.sh"
        run curl -fsSL "$DOCKER_INSTALL_URL" -o "$tmp"
        run as_root sh "$tmp"
        DOCKER_INSTALLED_NOW=true
    fi
    if command -v systemctl > /dev/null 2>&1; then
        if systemctl is-enabled docker > /dev/null 2>&1 && systemctl is-active docker > /dev/null 2>&1; then
            skip "docker.service is enabled and running"
        else
            run as_root systemctl enable --now docker      # services come back after a reboot
        fi
    fi
    if [ "$EUID" -eq 0 ]; then
        note "running as root: no docker group change (add the operator later: usermod -aG docker <user>)"
    elif in_docker_group; then
        skip "$OPERATOR is in group docker"
    else
        run as_root usermod -aG docker "$OPERATOR"
        GROUP_ADDED_NOW=true
    fi
}

# Can this shell talk to the daemon? Right after usermod the login session still lacks the
# group, so the rest of the install is re-run under sg(1) with the docker group.
ensure_docker_access() {
    docker info > /dev/null 2>&1 && return 0
    if $DRY_RUN; then
        note "the Docker daemon is not reachable from this shell (expected before an install or re-login)"
        return 0
    fi
    if [ "$EUID" -ne 0 ] && in_docker_group && [ -z "${LMS_INSTALL_REEXEC:-}" ] && command -v sg > /dev/null 2>&1; then
        note "docker group membership is new for this login session: continuing under 'sg docker'"
        export LMS_INSTALL_REEXEC=1
        rm -rf "$WORK"
        exec sg docker -c "$(fmt "$SCRIPT_PATH" "${ORIG_ARGS[@]}")"
    fi
    die "cannot reach the Docker daemon as $OPERATOR. Log out and back in (new group membership), then run the same command again: it continues where it stopped."
}

# ---------------------------------------------------------------------------- 3. folders
# OMV mounts data disks under /srv/dev-disk-by-*/. If that mount is missing, refuse rather
# than silently create the folder on the system disk.
guard_mount() {
    local dir="$1" mount
    case "$dir" in
        /srv/dev-disk-by-*)
            mount="${dir#/srv/}"; mount="/srv/${mount%%/*}"
            if ! { [ -d "$mount" ] && mountpoint -q "$mount" 2>/dev/null; }; then
                stop "$mount is not a mounted disk; refusing to create $dir on the system disk. Mount the data disk in OMV first (never reformat or repurpose a disk without a backup and the owner's approval, PRD section 11.1)"
            fi
            ;;
    esac
}
ensure_dir() {   # ensure_dir PATH MODE LABEL
    local dir="$1" mode="$2" label="$3" perms
    if [ -d "$dir" ]; then
        skip "$label exists: $dir (owner and permissions left as they are)"
        if [ "$label" = "video library" ]; then
            perms="$(stat -c %a "$dir" 2>/dev/null || true)"
            case "$perms" in
                ""|*[57]) ;;   # others may read and enter
                *) warn "$dir has mode $perms: the containers read it as a non-root user, so playback may fail with 403 until others can read and enter it (chmod o+rX)" ;;
            esac
        fi
        return 0
    fi
    guard_mount "$dir"
    run as_root install -d -m "$mode" -o "$OPERATOR" -g "$OPERATOR_GROUP" "$dir"
    $DRY_RUN || ok "$label created: $dir (owner $OPERATOR, mode $mode)"
}
create_folders() {
    section "3/7 Folders"
    ensure_dir "$VIDEO_ROOT" 755 "video library"
    ensure_dir "$BACKUP_DIR" 700 "backup folder"
    note "folders only: no disk was formatted, partitioned or mounted"
}

# ---------------------------------------------------------------------------- 4. .env
# Decide the effective settings before anything is created. An existing .env wins over the
# command line unless --force: it is the configuration the running stack uses.
resolve_settings() {
    local from_env
    if [ -f .env ] && ! $FORCE; then
        from_env="$(env_get VIDEO_ROOT)"
        case "$from_env" in
            ""|replace-with*) VIDEO_ROOT="${VIDEO_ROOT_ARG:-$DEFAULT_VIDEO_ROOT}" ;;
            *)
                VIDEO_ROOT="${from_env%/}"
                [ -z "$VIDEO_ROOT_ARG" ] || [ "$VIDEO_ROOT_ARG" = "$VIDEO_ROOT" ] \
                    || warn "--video-root $VIDEO_ROOT_ARG ignored: .env already sets VIDEO_ROOT=$VIDEO_ROOT (use --force to regenerate .env)"
                ;;
        esac
        MEDIA_BASE_URL="$(env_get MEDIA_BASE_URL)"
        [ -z "$MEDIA_BASE_URL_ARG" ] || [ "$MEDIA_BASE_URL_ARG" = "$MEDIA_BASE_URL" ] \
            || warn "--media-base-url $MEDIA_BASE_URL_ARG ignored: .env already sets MEDIA_BASE_URL='$MEDIA_BASE_URL' (use --force)"
    else
        VIDEO_ROOT="${VIDEO_ROOT_ARG:-$DEFAULT_VIDEO_ROOT}"
    fi
    LMS_HTTP_PORT="$(env_get LMS_HTTP_PORT)"; LMS_HTTP_PORT="${LMS_HTTP_PORT:-80}"
    LAN_IP="$(detect_lan_ip)"
}
# uid (%u) or gid (%g) owning the content folder: the API container runs as that user so
# files from the dashboard and from the network share can be edited by both.
content_owner() {
    stat -c "$1" "$VIDEO_ROOT" 2>/dev/null || { [ "$1" = %u ] && id -u || id -g; }
}
generate_secret() {
    if $DRY_RUN; then printf '%s' "<generated>"; return 0; fi
    "$PYTHON" -c "import secrets; print(secrets.token_urlsafe(48))"
}
valid_secret() { [[ "$1" =~ ^[A-Za-z0-9_-]{32,}$ ]]; }
configure_env() {
    section "4/7 Configuration (deploy/.env)"
    local pg_pw="" signing="" old_pg="" old_sign="" tmp port_suffix=""

    if [ -f .env ] && ! $FORCE; then
        skip ".env exists and is kept (--force regenerates it; secrets are kept). VIDEO_ROOT=$VIDEO_ROOT MEDIA_BASE_URL='${MEDIA_BASE_URL:-<empty>}'"
        [ -n "$(env_get POSTGRES_PASSWORD)" ] && [ -n "$(env_get MEDIA_SIGNING_SECRET)" ] \
            || stop ".env has no POSTGRES_PASSWORD or MEDIA_SIGNING_SECRET; fix it or re-run with --force"
        case "$(stat -c %a .env 2>/dev/null || echo 600)" in 600|400) ;; *) run chmod 600 .env ;; esac
        if [ -z "$(env_get LMS_CONTENT_UID)" ]; then
            if $DRY_RUN; then
                say "would  add LMS_CONTENT_UID/LMS_CONTENT_GID (owner of $VIDEO_ROOT) to .env"
            else
                set_env_var .env LMS_CONTENT_UID "$(content_owner %u)"
                set_env_var .env LMS_CONTENT_GID "$(content_owner %g)"
                ok "the API writes content as the owner of $VIDEO_ROOT (uid $(content_owner %u), gid $(content_owner %g))"
            fi
        fi
        return 0
    fi

    if [ -z "$MEDIA_BASE_URL_ARG" ]; then
        [ "$LMS_HTTP_PORT" = 80 ] || port_suffix=":$LMS_HTTP_PORT"
        if [ -n "$LAN_IP" ]; then
            MEDIA_BASE_URL="http://$LAN_IP$port_suffix"
            say "       Playback URLs need a fixed server address (MEDIA_BASE_URL). Detected LAN address: $LAN_IP"
            say "       Tablets will use $MEDIA_BASE_URL. Give the host a fixed IP or a DHCP reservation."
            confirm "Use $MEDIA_BASE_URL as MEDIA_BASE_URL (otherwise pass --media-base-url)?" \
                || die "Cancelled: re-run with --media-base-url http://<ip-or-hostname>."
        else
            warn "could not detect a LAN address; MEDIA_BASE_URL stays empty (each tablet's typed address is used). Set it later in .env."
            MEDIA_BASE_URL=""
        fi
    else
        MEDIA_BASE_URL="$MEDIA_BASE_URL_ARG"
    fi

    if [ -f .env ]; then      # --force: keep working secrets, the database volume was initialised with them
        old_pg="$(env_get POSTGRES_PASSWORD)"; old_sign="$(env_get MEDIA_SIGNING_SECRET)"
        if valid_secret "$old_pg"; then
            pg_pw="$old_pg"; note "keeping the existing POSTGRES_PASSWORD (the database volume was initialised with it)"
        fi
        if valid_secret "$old_sign"; then
            signing="$old_sign"; note "keeping the existing MEDIA_SIGNING_SECRET"
        fi
        warn "--force: other settings in .env return to the .env.example defaults"
        keep_copy .env env
    fi
    [ -n "$pg_pw" ] || pg_pw="$(generate_secret)"
    [ -n "$signing" ] || signing="$(generate_secret)"

    if $DRY_RUN; then
        say "would  write .env from .env.example (mode 600) with:"
        say "        | POSTGRES_PASSWORD=$pg_pw      ($PYTHON secrets.token_urlsafe(48))"
        say "        | MEDIA_SIGNING_SECRET=$signing   ($PYTHON secrets.token_urlsafe(48))"
        say "        | VIDEO_ROOT=$VIDEO_ROOT"
        say "        | MEDIA_BASE_URL=$MEDIA_BASE_URL"
        return 0
    fi
    tmp="$WORK/env.new"
    ( umask 077; tr -d '\r' < .env.example > "$tmp" )
    set_env_var "$tmp" POSTGRES_PASSWORD "$pg_pw"
    set_env_var "$tmp" MEDIA_SIGNING_SECRET "$signing"
    set_env_var "$tmp" VIDEO_ROOT "$VIDEO_ROOT"
    set_env_var "$tmp" MEDIA_BASE_URL "$MEDIA_BASE_URL"
    set_env_var "$tmp" LMS_CONTENT_UID "$(content_owner %u)"
    set_env_var "$tmp" LMS_CONTENT_GID "$(content_owner %g)"
    chmod 600 "$tmp"
    mv -f "$tmp" .env
    ok ".env written (mode 600): VIDEO_ROOT=$VIDEO_ROOT MEDIA_BASE_URL='${MEDIA_BASE_URL:-<empty>}', secrets generated"
}

# ---------------------------------------------------------------------------- 5. access control
DEFAULT_ALLOWLIST_RULES='allow 127.0.0.1;
allow 10.0.0.0/8;
allow 172.16.0.0/12;
allow 192.168.0.0/16;
deny all;'
allowlist_rules() {   # the effective lines of an allowlist (no comments, blanks or CRs)
    tr -d '\r' < "$1" | sed 's/#.*//; s/[[:space:]]\+/ /g; s/^ //; s/ $//' | grep -v '^$' || true
}
render_allowlist() {
    local cidr
    cat <<EOF
# Networks allowed to reach the LMS. $ALLOWLIST_MARKER on $STAMP.
# To change it: deploy/install.sh --allow <cidr> ... --force  (or edit by hand), then
#   docker compose restart nginx
# Keep 172.16.0.0/12: Docker's own bridge networks use it (the container healthcheck
# and the API's /ready check come from there).
allow 127.0.0.1;
allow 172.16.0.0/12;
EOF
    for cidr in "${ALLOW[@]}"; do printf 'allow %s;\n' "$cidr"; done
    printf 'deny all;\n'
}
configure_allowlist() {
    local file=nginx/allowlist.conf tmp current
    if [ ${#ALLOW[@]} -eq 0 ]; then
        if [ "$(allowlist_rules "$file")" = "$DEFAULT_ALLOWLIST_RULES" ]; then
            warn "$file still allows every private network (10/8, 172.16/12, 192.168/16): re-run with --allow <campus subnet> to narrow it"
        else
            skip "$file left as it is (no --allow given)"
        fi
        return 0
    fi
    tmp="$WORK/allowlist.conf"
    render_allowlist > "$tmp"
    if [ "$(allowlist_rules "$file")" = "$(allowlist_rules "$tmp")" ]; then
        skip "$file already allows exactly: ${ALLOW[*]} (plus 127.0.0.1 and Docker's 172.16.0.0/12)"
        return 0
    fi
    current="$(allowlist_rules "$file")"
    if [ "$current" != "$DEFAULT_ALLOWLIST_RULES" ] && ! $FORCE; then
        say "       current rules:"; printf '%s\n' "$current" | sed 's/^/         /'
        die "$file was edited and differs from the repository default; re-run with --force to replace it (a copy is kept in backups/)"
    fi
    [ "$current" = "$DEFAULT_ALLOWLIST_RULES" ] || keep_copy "$file" allowlist.conf
    if $DRY_RUN; then
        say "would  write $file:"; sed 's/^/        | /' "$tmp"
    else
        chmod 644 "$tmp"
        mv -f "$tmp" "$file"
        ok "$file now allows: ${ALLOW[*]} (plus 127.0.0.1 and Docker's 172.16.0.0/12)"
    fi
    # A running Nginx reads the include only at start; restart it once the stack is up.
    if docker compose ps -q nginx 2>/dev/null | grep -q .; then RESTART_NGINX=true; fi
}
render_firewall_script() {
    local cidr
    cat <<EOF
#!/bin/sh
# Campus LMS: only the campus subnets may reach the published LMS port. Docker-published
# ports bypass INPUT/ufw rules and OMV's firewall page; the DOCKER-USER chain is the place
# to filter them (docs/setup-guide.md section 4). $ALLOWLIST_MARKER on $STAMP;
# re-run install.sh --firewall --allow ... to change it. To remove the rules:
#   iptables -S DOCKER-USER | grep -- '--ctorigdstport $LMS_HTTP_PORT' | sed 's/^-A/-D/' | xargs -L1 iptables
set -e
IFACE=$(fmt "$IFACE")
PORT=$LMS_HTTP_PORT
iptables -N DOCKER-USER 2>/dev/null || true     # normally created by dockerd
rule() { iptables -C DOCKER-USER "\$@" 2>/dev/null || iptables -I DOCKER-USER "\$@"; }
# The DROP goes in first; each allowed subnet is then inserted above it.
rule -i "\$IFACE" -p tcp -m conntrack --ctorigdstport "\$PORT" --ctdir ORIGINAL -j DROP
EOF
    for cidr in "${ALLOW[@]}"; do
        # shellcheck disable=SC2016  # $IFACE and $PORT are expanded by the generated script
        printf 'rule -i "$IFACE" -p tcp -m conntrack --ctorigdstport "$PORT" --ctdir ORIGINAL -s %s -j RETURN\n' "$cidr"
    done
}
render_firewall_unit() {
    cat <<EOF
# $ALLOWLIST_MARKER on $STAMP. Re-applies the DOCKER-USER rules after every boot and
# every Docker restart (the chain only exists once dockerd runs).
[Unit]
Description=Campus LMS firewall rules (DOCKER-USER chain)
After=docker.service
Wants=docker.service
PartOf=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=$FIREWALL_SCRIPT

[Install]
WantedBy=multi-user.target
EOF
}
configure_firewall() {
    if ! $FIREWALL; then
        note "no host firewall rule (--firewall): Docker-published ports bypass ufw/INPUT rules, so only allowlist.conf filters clients"
        return 0
    fi
    command -v iptables > /dev/null 2>&1 || $DRY_RUN || die "iptables is not installed (Docker normally brings it); install it and re-run with --firewall"
    command -v systemctl > /dev/null 2>&1 || $DRY_RUN || die "--firewall needs systemd to make the rule persistent"
    if [ -z "$IFACE" ]; then
        IFACE="$(detect_iface)"
        if [ -z "$IFACE" ]; then
            $DRY_RUN || die "could not detect the LAN interface; pass --iface <name> (see: ip -4 addr)"
            IFACE="<lan-interface>"
        fi
        note "firewall rule on interface $IFACE (override with --iface)"
    fi
    CHANGED=false
    write_root_file "$FIREWALL_SCRIPT" 755 "$(render_firewall_script)"
    write_root_file "$FIREWALL_UNIT" 644 "$(render_firewall_unit)"
    if $CHANGED || ! systemctl is-active campus-lms-firewall.service > /dev/null 2>&1; then
        run as_root systemctl daemon-reload
        run as_root systemctl enable campus-lms-firewall.service
        run as_root systemctl restart campus-lms-firewall.service
    else
        skip "campus-lms-firewall.service is active"
    fi
    if ! $DRY_RUN; then
        say "       DOCKER-USER rules now:"
        as_root iptables -S DOCKER-USER | sed 's/^/         /'
    fi
}
configure_access() {
    section "5/7 Access control (nginx/allowlist.conf, host firewall)"
    configure_allowlist
    configure_firewall
}

# ---------------------------------------------------------------------------- 6. start
wait_healthy() {
    local deadline=$((SECONDS + HEALTH_TIMEOUT)) status healthy bad svc
    say "       waiting up to ${HEALTH_TIMEOUT}s for db, api and nginx to report healthy ..."
    while :; do
        status="$(docker compose ps -a --format '{{.Service}} {{.State}} {{.Health}}' 2>/dev/null | tr -d '\r')"
        healthy="$(printf '%s\n' "$status" | awk '$2 == "running" && $3 == "healthy" {n++} END {print n + 0}')"
        bad="$(printf '%s\n' "$status" | awk '$2 == "exited" || $2 == "dead" || $3 == "unhealthy" {print $1}')"
        if [ "$healthy" -ge 3 ]; then
            say ""; ok "db, api and nginx are healthy"
            docker compose ps --format 'table {{.Service}}\t{{.State}}\t{{.Status}}\t{{.Ports}}'
            return 0
        fi
        if [ -n "$bad" ]; then
            say ""; docker compose ps -a
            printf '%s\n' "$bad" | while read -r svc; do
                say "--- last 40 log lines of $svc ---"
                docker compose logs --no-color --tail 40 "$svc" || true
            done
            die "service(s) failed to start: $(printf '%s' "$bad" | tr '\n' ' ')"
        fi
        if [ "$SECONDS" -ge "$deadline" ]; then
            say ""; docker compose ps -a
            die "services not healthy after ${HEALTH_TIMEOUT}s; see: docker compose logs api nginx db"
        fi
        printf '.'; sleep 5
    done
}
start_stack() {
    section "6/7 Start the stack"
    run docker compose up -d --build
    if $DRY_RUN; then
        say "would  wait up to ${HEALTH_TIMEOUT}s for db, api and nginx to be healthy"
        $RESTART_NGINX && say "would  docker compose restart nginx (allowlist changed)"
        return 0
    fi
    wait_healthy
    if $RESTART_NGINX; then
        run docker compose restart nginx
        wait_healthy
    fi
}

