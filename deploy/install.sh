#!/usr/bin/env bash
# One-command install of the Campus LMS prototype on a fresh Debian 12/13, Ubuntu 24.04 or
# OpenMediaVault 7/8 host: docs/setup-guide.md sections 2-6 and 8 (the M1 step, PRD §17).
# Run it as the sudo-capable operator account that will run the stack, from a checkout:
#
#   deploy/install.sh --dry-run                               # only show what would be done
#   deploy/install.sh --allow 192.168.10.0/24                 # fresh host, default folders
#   deploy/install.sh --video-root /srv/dev-disk-by-uuid-XXXX/campus-lms/videos \
#       --media-base-url http://lms.campus.lan --allow 192.168.10.0/24 --allow 10.20.0.0/16 \
#       --firewall --demo                                     # OMV shared folder, firewall, demo data
#
# Every step is skipped when it is already done, so the script can be re-run after a
# failure or later with --demo or --firewall. It creates folders only: it never formats,
# partitions or mounts a disk (PRD §11.1). An existing .env or a hand-edited
# nginx/allowlist.conf is not overwritten without --force (the old file is kept in backups/).
set -euo pipefail
export MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*'

SCRIPT_PATH="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
ORIG_ARGS=("$@")
cd "$(dirname "$0")"        # deploy/

DOCKER_INSTALL_URL=https://get.docker.com
DEFAULT_VIDEO_ROOT=/srv/campus-lms/videos
DEFAULT_BACKUP_DIR=/srv/backups/lms         # docs/backup-restore.md
FIREWALL_SCRIPT=/usr/local/sbin/campus-lms-firewall
FIREWALL_UNIT=/etc/systemd/system/campus-lms-firewall.service
ALLOWLIST_MARKER='Generated by deploy/install.sh'
HEALTH_TIMEOUT=300          # seconds to wait for db, api and nginx
MIN_DOCKER_FREE_GIB=5       # images, build cache and the database volume
MIN_VIDEO_FREE_GIB=10       # warning only: the demo videos need ~0.3 GB, real lessons more

usage() {
    cat <<EOF
Usage: deploy/install.sh [options]

Installs the Campus LMS stack on this host (docs/setup-guide.md sections 2-6 and 8):
prerequisites, Docker, folders, deploy/.env, access control, docker compose up, checks.

Options:
  --video-root PATH     Host folder for the MP4 library (default $DEFAULT_VIDEO_ROOT).
                        On OMV: the shared folder's path, e.g. /srv/dev-disk-by-uuid-XXXX/campus-lms/videos
  --backup-dir PATH     Folder for scripts/backup.sh output (default $DEFAULT_BACKUP_DIR)
  --media-base-url URL  Base for playback URLs, e.g. http://192.168.10.10 or http://lms.campus.lan
                        (default: this host's primary LAN address, shown for confirmation)
  --allow CIDR          Subnet allowed to reach the LMS; repeatable. Rewrites nginx/allowlist.conf
                        (the Docker 172.16.0.0/12 line is kept)
  --firewall            Also filter the published port in the DOCKER-USER chain and make the rule
                        persistent (systemd unit $FIREWALL_UNIT). Needs --allow
  --iface NAME          LAN interface for the firewall rule (default: the default route's interface)
  --demo                Generate the short demo videos and seed the demo accounts (asks for the
                        demo password)
  --force               Replace an existing .env (its secrets are kept) or a hand-edited
                        allowlist.conf; the old file is copied to deploy/backups/
  -y, --yes             Answer yes to confirmations (Docker install, detected address)
  -n, --dry-run         Show what would be done without changing anything
  -h, --help            This text
EOF
}

