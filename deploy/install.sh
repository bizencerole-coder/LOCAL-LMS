valid_cidr() {
    local addr="${1%/*}" bits="${1#*/}" octet octets
    [[ "$1" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}(/[0-9]{1,2})?$ ]] || return 1
    [ "$addr" != "$1" ] || bits=32
    [ "$bits" -le 32 ] || return 1
    IFS=. read -r -a octets <<< "$addr"
    for octet in "${octets[@]}"; do [ "$octet" -le 255 ] || return 1; done
}
valid_url() { [[ "$1" =~ ^https?://[A-Za-z0-9._-]+(:[0-9]{1,5})?$ ]]; }

while [ $# -gt 0 ]; do
    case "$1" in
        --video-root)      VIDEO_ROOT_ARG="${2:?$1 needs a path}"; shift ;;
        --video-root=*)    VIDEO_ROOT_ARG="${1#*=}" ;;
        --backup-dir)      BACKUP_DIR="${2:?$1 needs a path}"; shift ;;
        --backup-dir=*)    BACKUP_DIR="${1#*=}" ;;
        --media-base-url)  MEDIA_BASE_URL_ARG="${2:?$1 needs a URL}"; shift ;;
        --media-base-url=*) MEDIA_BASE_URL_ARG="${1#*=}" ;;
        --allow)           ALLOW+=("${2:?$1 needs a CIDR}"); shift ;;
        --allow=*)         ALLOW+=("${1#*=}") ;;
        --iface)           IFACE="${2:?$1 needs an interface name}"; shift ;;
        --iface=*)         IFACE="${1#*=}" ;;
        --firewall)        FIREWALL=true ;;
        --demo)            DEMO=true ;;
        --force)           FORCE=true ;;
        -y|--yes)          ASSUME_YES=true ;;
        -n|--dry-run)      DRY_RUN=true ;;
        -h|--help)         usage; exit 0 ;;
        *) echo "Unknown option: $1" >&2; echo "Try: $0 --help" >&2; exit 2 ;;
    esac
    shift
done

for cidr in "${ALLOW[@]}"; do
    valid_cidr "$cidr" || { echo "--allow: '$cidr' is not an IPv4 address or CIDR (e.g. 192.168.10.0/24)" >&2; exit 2; }
done
if [ -n "$VIDEO_ROOT_ARG" ]; then
    VIDEO_ROOT_ARG="${VIDEO_ROOT_ARG%/}"
    case "$VIDEO_ROOT_ARG" in /*) ;; *) echo "--video-root must be an absolute path" >&2; exit 2 ;; esac
fi
BACKUP_DIR="${BACKUP_DIR%/}"
case "$BACKUP_DIR" in /*) ;; *) echo "--backup-dir must be an absolute path" >&2; exit 2 ;; esac
if [ -n "$MEDIA_BASE_URL_ARG" ]; then
    MEDIA_BASE_URL_ARG="${MEDIA_BASE_URL_ARG%/}"
    valid_url "$MEDIA_BASE_URL_ARG" || { echo "--media-base-url must look like http://192.168.10.10 or http://lms.campus.lan[:port]" >&2; exit 2; }
fi
if $FIREWALL && [ ${#ALLOW[@]} -eq 0 ]; then
    echo "--firewall needs at least one --allow <subnet> (the subnets that may reach the LMS)" >&2; exit 2
fi
if [ -n "$IFACE" ] && ! $FIREWALL; then
    echo "--iface only applies with --firewall" >&2; exit 2
fi

# ---------------------------------------------------------------------------- helpers
say()     { printf '%s\n' "$*"; }
section() { printf '\n== %s ==\n' "$1"; }
ok()      { say "ok     $*"; }
skip()    { say "skip   $*"; }
note()    { say "note   $*"; }
warn()    { say "WARN   $*" >&2; }
die()     { say "ERROR  $*" >&2; exit 1; }

DRY_FAILS=0
# A check that would stop a real run. With --dry-run it is reported and the run continues,
# so the whole plan is shown even on a machine that is not the target host.
stop() {
    if $DRY_RUN; then say "FAIL   $* (a real run stops here)"; DRY_FAILS=$((DRY_FAILS + 1)); else die "$*"; fi
}

# Shell-quoted rendering of a command, for progress lines and the sg re-exec.
fmt() {
    local out="" arg
    for arg in "$@"; do out+="$(printf '%q' "$arg") "; done
    printf '%s' "${out% }"
}
# Run as root: directly when already root, otherwise through sudo.
as_root() { if [ "$EUID" -eq 0 ]; then "$@"; else sudo "$@"; fi; }
# Run a command and show it, or only show it with --dry-run.
run() {
    local shown=("$@")
    if [ "${shown[0]}" = as_root ]; then
        shown=("${shown[@]:1}")
        [ "$EUID" -eq 0 ] || shown=(sudo "${shown[@]}")
    fi
    if $DRY_RUN; then say "would  $(fmt "${shown[@]}")"; return 0; fi
    say "+ $(fmt "${shown[@]}")"
    "$@"
}
# confirm "question" -> 0 for yes. --yes and --dry-run answer yes.
confirm() {
    local answer
    if $ASSUME_YES; then say "yes    $1 (--yes)"; return 0; fi
    if $DRY_RUN; then say "would  ask: $1"; return 0; fi
    [ -t 0 ] || die "$1 -- no terminal to answer on; re-run with --yes"
    read -r -p "$1 [y/N] " answer
    case "$answer" in y|Y|yes|YES|Yes) return 0 ;; *) return 1 ;; esac
}
# Value from .env unless the shell already sets it (Compose precedence); strips CR and quotes.
env_get() {
    local name="$1" value
    value="${!name:-}"
    if [ -z "$value" ] && [ -f .env ]; then
        value="$(grep -E "^$name=" .env | tail -1 | cut -d= -f2- | tr -d '\r"'"'")"
    fi
    printf '%s' "$value"
}
# set_env_var FILE KEY VALUE: replace the KEY= line(s) or append one.
set_env_var() {
    local file="$1" key="$2" value="$3" line found=0 tmp
    tmp="$WORK/env.tmp"
    while IFS= read -r line || [ -n "$line" ]; do
        case "$line" in
            "$key="*) printf '%s=%s\n' "$key" "$value"; found=1 ;;
            *)        printf '%s\n' "$line" ;;
        esac
    done < "$file" > "$tmp"
    [ $found -eq 1 ] || printf '%s=%s\n' "$key" "$value" >> "$tmp"
    cat "$tmp" > "$file"
}
# Write a root-owned file unless it already has exactly this content. Sets CHANGED=true.
write_root_file() {
    local path="$1" mode="$2" content="$3"
    if [ -f "$path" ] && [ "$(cat "$path")" = "$content" ]; then skip "$path is up to date"; return 0; fi
    CHANGED=true
    if $DRY_RUN; then
        say "would  write $path (mode $mode):"
        printf '%s\n' "$content" | sed 's/^/        | /'
        return 0
    fi
    say "+ write $path (mode $mode)"
    printf '%s\n' "$content" | as_root tee "$path" > /dev/null
    as_root chmod "$mode" "$path"
}
free_gib() { df -Pk "$1" 2>/dev/null | awk 'NR == 2 {printf "%d", $4 / 1048576}'; }
existing_ancestor() {
    local path="$1"
    while [ ! -d "$path" ] && [ "$path" != / ]; do path="$(dirname "$path")"; done
    printf '%s' "$path"
}
find_python() {
    local candidate
    for candidate in python3 python; do
        if command -v "$candidate" > /dev/null 2>&1 \
            && "$candidate" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 10) else 1)' > /dev/null 2>&1; then
            printf '%s' "$candidate"; return 0
        fi
    done
    return 1
}
detect_lan_ip() {
    local addr=""
    if command -v ip > /dev/null 2>&1; then
        # The source address of the default route; no packet is sent.
        addr="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for (i = 1; i <= NF; i++) if ($i == "src") {print $(i + 1); exit}}')"
        [ -n "$addr" ] || addr="$(ip -4 -o addr show scope global 2>/dev/null | awk 'NR == 1 {sub(/\/.*/, "", $4); print $4}')"
    fi
    [ -n "$addr" ] || addr="$(hostname -I 2>/dev/null | awk '{print $1}')"
    if [ -z "$addr" ] && command -v ipconfig > /dev/null 2>&1; then   # Windows / Git Bash: --dry-run only
        addr="$(ipconfig | tr -d '\r' | grep -a 'IPv4' | head -1 | sed 's/.*: *//')"
    fi
    printf '%s' "$addr"
}
detect_iface() {
    local dev=""
    if command -v ip > /dev/null 2>&1; then
        dev="$(ip -4 route show default 2>/dev/null | awk '{for (i = 1; i <= NF; i++) if ($i == "dev") {print $(i + 1); exit}}')"
        [ -n "$dev" ] || dev="$(ip -4 -o addr show scope global 2>/dev/null | awk 'NR == 1 {print $2}')"
    fi
    printf '%s' "$dev"
}
in_docker_group() { id -nG "$OPERATOR" 2>/dev/null | tr ' ' '\n' | grep -qx docker; }
keep_copy() {   # keep_copy FILE LABEL: copy FILE to backups/ before replacing it
    local file="$1" label="$2" dest
    dest="backups/$label.$STAMP.bak"
    if $DRY_RUN; then say "would  keep a copy of $file as $dest"; return 0; fi
    [ -d backups ] || ( umask 077; mkdir -p backups )     # as backup.sh does
    cp -p "$file" "$dest"
    chmod 600 "$dest"
    say "+ kept a copy of $file as $dest"
}

